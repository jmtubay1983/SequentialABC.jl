using SequentialABC
using Test
using Distributions

# ── tiny deterministic problem for `make_generation_job` ─────────────────────
# The `_hpc` suffix keeps this file's globals apart from the other suites that
# share one Main namespace.
_hpc_prior(θ) = 0.0
_hpc_sample_prior(rng) = [0.0]
_hpc_simulator = ContinuousSimulator(
    model_builder = θ -> θ,
    evolve = (θ, rng) -> θ,
    summary = identity,
)
CFG_HPC = ABCSMCConfig(_hpc_prior, _hpc_sample_prior, identity, l2_distance,
                       GaussianKernel(), [1.0 0.0; 0.0 1.0], _hpc_simulator)

@testset "HPC / Slurm helpers" begin

    # ── SlurmTemplate ────────────────────────────────────────────────────────
    @testset "SlurmTemplate construction and validation" begin
        t = SlurmTemplate()
        @test t.job_name == "abc"
        @test t.cpus == 1
        @test t.partition == ""
        @test t.modules == String[]
        @test t.env == Dict{String,String}()

        @test_throws ArgumentError SlurmTemplate(job_name = "")
        @test_throws ArgumentError SlurmTemplate(cpus = 0)
    end

    # ── render_slurm_script ──────────────────────────────────────────────────
    @testset "render_slurm_script layout" begin
        t = SlurmTemplate(job_name = "abc_gen_003", time = "02:00:00",
                          mem = "8G", cpus = 4, partition = "cpu",
                          modules = ["julia/1.13", "hpcx"],
                          env = Dict("A" => "1", "Z" => "26"))
        script = render_slurm_script(t, "julia run.jl")
        lines = split(script, '\n'; keepempty = false)

        @test lines[1] == "#!/bin/bash"
        @test "#SBATCH --job-name=abc_gen_003" in lines
        @test "#SBATCH --time=02:00:00" in lines
        @test "#SBATCH --mem=8G" in lines
        @test "#SBATCH --cpus-per-task=4" in lines
        @test "#SBATCH --partition=cpu" in lines
        @test lines[end] == "julia run.jl"       # command is last, never executed
        @test endswith(script, "julia run.jl\n")

        # modules keep their order; env is sorted by key
        @test findfirst(==("module load julia/1.13"), lines) <
              findfirst(==("module load hpcx"), lines)
        @test findfirst(==("export A=1"), lines) < findfirst(==("export Z=26"), lines)
    end

    @testset "partition omitted when empty" begin
        script = render_slurm_script(SlurmTemplate(), "true")
        @test !occursin("--partition", script)
    end

    @testset "extra_headers and comments" begin
        script = render_slurm_script(
            SlurmTemplate(), "true";
            extra_headers = ["--output=logs/%j.out", "#SBATCH --nodes=2"],
            comments = ["generated by test"],
        )
        lines = split(script, '\n'; keepempty = false)
        @test lines[2] == "# generated by test"     # comments right after shebang
        @test "#SBATCH --output=logs/%j.out" in lines   # prefix added
        @test "#SBATCH --nodes=2" in lines              # already a directive
        @test !occursin("#SBATCH #SBATCH", script)      # never double‑prefixed
    end

    @testset "render is byte-deterministic" begin
        t1 = SlurmTemplate(env = Dict("A" => "1", "B" => "2"))
        t2 = SlurmTemplate(env = Dict("B" => "2", "A" => "1"))  # different insertion order
        @test render_slurm_script(t1, "cmd") == render_slurm_script(t1, "cmd")
        @test render_slurm_script(t1, "cmd") == render_slurm_script(t2, "cmd")
    end

    # ── write_slurm_script ───────────────────────────────────────────────────
    @testset "write_slurm_script writes exactly the rendered text" begin
        mktempdir() do dir
            t = SlurmTemplate(job_name = "abc")
            path = joinpath(dir, "nested", "abc.sbatch")
            @test write_slurm_script(path, t, "julia run.jl") == path
            @test isfile(path)
            @test read(path, String) == render_slurm_script(t, "julia run.jl")
        end
    end

    # ── make_generation_job ──────────────────────────────────────────────────
    @testset "make_generation_job: deterministic names and command" begin
        mktempdir() do dir
            (path, name) = make_generation_job(
                CFG_HPC, 3;
                template = SlurmTemplate(job_name = "abc"),
                config_path = "cli_config.jl",
                checkpoint_dir = "ckpt",
                script_dir = dir,
            )
            @test name == "abc_gen_003"
            @test path == joinpath(dir, "abc_gen_003.sbatch")
            @test isfile(path)

            # same cfg + gen → same bytes every time
            (path2, name2) = make_generation_job(
                CFG_HPC, 3;
                template = SlurmTemplate(job_name = "abc"), script_dir = dir,
                config_path = "cli_config.jl", checkpoint_dir = "ckpt",
            )
            @test (path2, name2) == (path, name)
            @test read(path, String) == read(path2, String)

            script = read(path, String)
            @test occursin("--config cli_config.jl", script)
            @test occursin("--checkpoint-dir ckpt", script)
            @test occursin("--target-gen 3", script)
            @test occursin("#SBATCH --job-name=abc_gen_003", script)
            @test occursin("simulator: ContinuousSimulator", script)
            @test endswith(script, "--target-gen 3\n")
        end
    end

    @testset "make_generation_job rejects gen < 1" begin
        mktempdir() do dir
            @test_throws ArgumentError make_generation_job(CFG_HPC, 0; script_dir = dir)
        end
    end

    # ── collect_checkpoints! ─────────────────────────────────────────────────
    @testset "collect_checkpoints!: copy, filter, sort" begin
        mktempdir() do dir
            src = joinpath(dir, "src"); mkpath(src)
            for f in ["state_gen_001.jls", "state_gen_002.jls", "notes.txt",
                      "state_gen_003.jls.tmp"]
                write(joinpath(src, f), "dummy")
            end
            dest = joinpath(dir, "archive")
            got = collect_checkpoints!(dest, src)

            @test got == sort([joinpath(dest, "state_gen_001.jls"),
                               joinpath(dest, "state_gen_002.jls")])
            @test all(isfile, got)
            @test !isfile(joinpath(dest, "notes.txt"))       # non-matching ignored
            @test !isfile(joinpath(dest, "state_gen_003.jls.tmp"))
            @test isfile(joinpath(src, "state_gen_001.jls")) # :copy keeps the source
            @test read(joinpath(dest, "state_gen_001.jls"), String) == "dummy"
            # the collected names are exactly what list_checkpoints understands
            @test [basename(p) for (_, p) in list_checkpoints(dest)] ==
                  ["state_gen_001.jls", "state_gen_002.jls"]
        end
    end

    @testset "collect_checkpoints!: :move empties the source" begin
        mktempdir() do dir
            src = joinpath(dir, "src"); mkpath(src)
            write(joinpath(src, "state_gen_005.jls"), "x")
            dest = joinpath(dir, "archive")
            got = collect_checkpoints!(dest, src; mode = :move)
            @test got == [joinpath(dest, "state_gen_005.jls")]
            @test isfile(got[1])
            @test !isfile(joinpath(src, "state_gen_005.jls"))
        end
    end

    @testset "collect_checkpoints!: several source directories" begin
        mktempdir() do dir
            a = joinpath(dir, "run_1"); b = joinpath(dir, "run_2")
            mkpath(a); mkpath(b)
            write(joinpath(a, "state_gen_001.jls"), "a1")
            write(joinpath(b, "state_gen_002.jls"), "b2")
            dest = joinpath(dir, "archive")
            # a missing source directory is skipped, not an error
            got = collect_checkpoints!(dest, [a, joinpath(dir, "missing"), b])
            @test got == [joinpath(dest, "state_gen_001.jls"),
                          joinpath(dest, "state_gen_002.jls")]   # sorted
            @test read(joinpath(dest, "state_gen_001.jls"), String) == "a1"
            @test read(joinpath(dest, "state_gen_002.jls"), String) == "b2"
        end
    end

    @testset "collect_checkpoints!: collisions are errors, never overwrites" begin
        mktempdir() do dir
            a = joinpath(dir, "run_1"); b = joinpath(dir, "run_2")
            mkpath(a); mkpath(b)
            write(joinpath(a, "state_gen_001.jls"), "a1")
            write(joinpath(b, "state_gen_001.jls"), "b1")
            @test_throws ArgumentError collect_checkpoints!(joinpath(dir, "archive"), [a, b])

            # pre-existing destination file: also an error
            dest = joinpath(dir, "archive2"); mkpath(dest)
            write(joinpath(dest, "state_gen_001.jls"), "old")
            @test_throws ArgumentError collect_checkpoints!(dest, a)
            @test read(joinpath(dest, "state_gen_001.jls"), String) == "old"
        end
    end

    @testset "collect_checkpoints!: argument validation" begin
        mktempdir() do dir
            @test_throws ArgumentError collect_checkpoints!(dir, dir; mode = :link)
            @test_throws ArgumentError collect_checkpoints!(dir, dir; pattern = "no-wildcard.jls")
            @test collect_checkpoints!(dir, dir) == String[]   # nothing to collect
        end
    end

    # ── simulate_slurm_submission_preview ────────────────────────────────────
    @testset "submission preview is a string, nothing is submitted" begin
        t = SlurmTemplate(job_name = "abc_gen_003")
        @test simulate_slurm_submission_preview(t, "abc_gen_003.sbatch") ==
              "sbatch --job-name=abc_gen_003 abc_gen_003.sbatch"
        @test simulate_slurm_submission_preview(t, "job.sbatch"; deps = "12345") ==
              "sbatch --job-name=abc_gen_003 --dependency=afterok:12345 job.sbatch"
        @test simulate_slurm_submission_preview(t, "job.sbatch"; deps = ["1", "2"]) ==
              "sbatch --job-name=abc_gen_003 --dependency=afterok:1:2 job.sbatch"
        @test_throws ArgumentError simulate_slurm_submission_preview(t, "job.sbatch"; deps = String[])
    end
end
